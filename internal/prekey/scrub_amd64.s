	MOVOU X4, 64(DI)
	MOVOU X5, 80(DI)
	MOVOU X6, 96(DI)
	MOVOU X7, 112(DI)
	MOVOU X8, 128(DI)
	MOVOU X9, 144(DI)
	MOVOU X10, 160(DI)
	MOVOU X11, 176(DI)
	MOVOU X12, 192(DI)
	MOVOU X13, 208(DI)
	MOVOU X14, 224(DI)
	MOVOU X15, 240(DI)
	MOVB avx+8(FP), CX
	TESTB CX, CX
	JZ   done
	VEXTRACTF128 $1, Y0, X0
	MOVOU X0, 256(DI)
	VEXTRACTF128 $1, Y1, X0
	MOVOU X0, 272(DI)
	VEXTRACTF128 $1, Y2, X0
	MOVOU X0, 288(DI)
	VEXTRACTF128 $1, Y3, X0
	MOVOU X0, 304(DI)
	VEXTRACTF128 $1, Y4, X0
	MOVOU X0, 320(DI)
	VEXTRACTF128 $1, Y5, X0
	MOVOU X0, 336(DI)
	VEXTRACTF128 $1, Y6, X0
	MOVOU X0, 352(DI)
	VEXTRACTF128 $1, Y7, X0
	MOVOU X0, 368(DI)
	VEXTRACTF128 $1, Y8, X0
	MOVOU X0, 384(DI)
	VEXTRACTF128 $1, Y9, X0
	MOVOU X0, 400(DI)
	VEXTRACTF128 $1, Y10, X0
	MOVOU X0, 416(DI)
	VEXTRACTF128 $1, Y11, X0
	MOVOU X0, 432(DI)
	VEXTRACTF128 $1, Y12, X0
