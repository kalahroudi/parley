// func hasAVX() bool
// CPUID.1:ECX has OSXSAVE (27) and AVX (28), and XCR0 enables XMM and YMM state.
TEXT ·hasAVX(SB), NOSPLIT, $0-1
	MOVL $1, AX
	XORL CX, CX
	CPUID
	MOVL CX, DX
	ANDL $0x18000000, DX
	CMPL DX, $0x18000000
	JNE  no
	XORL CX, CX
	XGETBV
	ANDL $6, AX
	CMPL AX, $6
	JNE  no
	MOVB $1, ret+0(FP)
	RET
no:
	MOVB $0, ret+0(FP)
	RET

// func hasAVX512() bool
// AVX-512F (CPUID.7.0:EBX bit 16), and the OS saves the opmask, ZMM_Hi256 and
// Hi16_ZMM state (XCR0 bits 5-7) as well as XMM and YMM (bits 1-2). Leaf 7 must
// exist, and XGETBV is only legal once OSXSAVE is set.
TEXT ·hasAVX512(SB), NOSPLIT, $0-1
	XORL AX, AX
	CPUID
	CMPL AX, $7
	JB   no512
	MOVL $1, AX
	XORL CX, CX
	CPUID
	BTL  $27, CX
	JCC  no512
	XORL CX, CX
	XGETBV
	ANDL $0xE6, AX
	CMPL AX, $0xE6
	JNE  no512
	MOVL $7, AX
	XORL CX, CX
	CPUID
	BTL  $16, BX
	JCC  no512
	MOVB $1, ret+0(FP)
	RET
no512:
	MOVB $0, ret+0(FP)
	RET

// func scrubSSE()
// Zeroes the low 128 bits of X0-X15. A 32-byte copy of a scalar (memmove,
// SHA-256, ChaCha) leaves it in these registers, and a signal delivered later
// writes them to the signal stack, which is Go heap memory.
TEXT ·scrubSSE(SB), NOSPLIT, $0-0
	PXOR X0, X0
	PXOR X1, X1
	PXOR X2, X2
	PXOR X3, X3
	PXOR X4, X4
	PXOR X5, X5
	PXOR X6, X6
	PXOR X7, X7
	PXOR X8, X8
	PXOR X9, X9
	PXOR X10, X10
	PXOR X11, X11
	PXOR X12, X12
	PXOR X13, X13
	PXOR X14, X14
	PXOR X15, X15
	RET

// func scrubAVX()
// Zeroes all of Y0-Y15 (VZEROALL), including the upper halves SSE code leaves alone.
// It does nothing without AVX, so the Go caller needs no branch of its own (a
// branch on the CPU would make statement coverage depend on the runner).
TEXT ·scrubAVX(SB), NOSPLIT, $0-0
	CMPB ·haveAVX(SB), $0
	JEQ  noavx
	VZEROALL
noavx:
	RET

// func scrubAVX512()
// Zeroes Z0-Z31 (Z16-Z31 and the bits above 255 of Z0-Z15 are beyond VZEROALL
// on some readings of the manual, so they are cleared explicitly) and the mask
// registers K0-K7. Does nothing without AVX-512F.
TEXT ·scrubAVX512(SB), NOSPLIT, $0-0
	CMPB ·haveAVX512(SB), $0
	JEQ  no512
	VPXORQ Z0, Z0, Z0
	VPXORQ Z1, Z1, Z1
	VPXORQ Z2, Z2, Z2
	VPXORQ Z3, Z3, Z3
	VPXORQ Z4, Z4, Z4
	VPXORQ Z5, Z5, Z5
	VPXORQ Z6, Z6, Z6
	VPXORQ Z7, Z7, Z7
	VPXORQ Z8, Z8, Z8
	VPXORQ Z9, Z9, Z9
	VPXORQ Z10, Z10, Z10
	VPXORQ Z11, Z11, Z11
	VPXORQ Z12, Z12, Z12
	VPXORQ Z13, Z13, Z13
	VPXORQ Z14, Z14, Z14
	VPXORQ Z15, Z15, Z15
	VPXORQ Z16, Z16, Z16
	VPXORQ Z17, Z17, Z17
	VPXORQ Z18, Z18, Z18
	VPXORQ Z19, Z19, Z19
	VPXORQ Z20, Z20, Z20
	VPXORQ Z21, Z21, Z21
	VPXORQ Z22, Z22, Z22
	VPXORQ Z23, Z23, Z23
