package release

import (
	"bytes"
	"fmt"
	"path/filepath"
	"strings"
	"text/template"
)

// Homepage and download address of the project, used in the package files.
const (
	Homepage    = "https://github.com/kalahroudi/parley"
	downloadURL = Homepage + "/releases/download"
)

// brewTarget is one platform the Homebrew formula installs on.
type brewTarget struct {
	OS, Arch string // Go names
	Block    string // Homebrew's on_macos / on_linux
	CPU      string // on_arm / on_intel
}

var brewTargets = []brewTarget{
	{"darwin", "arm64", "on_macos", "on_arm"},
	{"darwin", "amd64", "on_macos", "on_intel"},
	{"linux", "arm64", "on_linux", "on_arm"},
	{"linux", "amd64", "on_linux", "on_intel"},
}

type brewFile struct{ URL, SHA string }

type brewPlatform struct {
	Block, CPU  string
	Daemon, CLI brewFile
}

var formulaTmpl = template.Must(template.New("formula").Parse(`# Generated by parley-release for {{.Tag}}; do not edit. The checksums are those of the signed SHA256SUMS.
class Parley < Formula
  desc "Secure agent-to-agent tasks between the bots of an organisation"
  homepage "{{.Homepage}}"
  version "{{.Version}}"
  license "Apache-2.0"
{{range .Platforms}}
  {{.Block}} do
    {{.CPU}} do
      url "{{.Daemon.URL}}"
      sha256 "{{.Daemon.SHA}}"

      resource "parley-cli" do
        url "{{.CLI.URL}}"
        sha256 "{{.CLI.SHA}}"
      end
    end
  end
{{end}}
  def install
    bin.install Dir["parleyd_*"].first => "parleyd"
    resource("parley-cli").stage { bin.install Dir["parley-cli_*"].first => "parley-cli" }
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/parleyd --version")
  end
end
`))

// Formula renders the Homebrew formula for the release tagged tag (vMAJOR.MINOR.PATCH) from the release
// binaries in dir, named as scripts/release.sh names them. Homebrew checks each download against the hash in
// the formula, which is taken from the very files that SHA256SUMS signs; the formula lives in the project's tap.
// parley-cli update does not touch a Homebrew install (internal/update refuses package-managed files): `brew
// upgrade` does.
func Formula(tag, dir string) ([]byte, error) {
	version, err := debVersion(tag)
	if err != nil {
		return nil, err
	}
	var plats []brewPlatform
	for _, t := range brewTargets {
		p := brewPlatform{Block: t.Block, CPU: t.CPU}
		for i, cmd := range []string{"parleyd", "parley-cli"} {
			name := fmt.Sprintf("%s_%s_%s_%s", cmd, tag, t.OS, t.Arch)
			sum, err := fileSum(filepath.Join(dir, name))
			if err != nil {
				return nil, err
			}
			f := brewFile{URL: downloadURL + "/" + tag + "/" + name, SHA: sum}
			if i == 0 {
				p.Daemon = f
			} else {
				p.CLI = f
			}
		}
		plats = append(plats, p)
	}
	var b bytes.Buffer
	err = formulaTmpl.Execute(&b, map[string]any{"Tag": tag, "Version": version, "Homepage": Homepage, "Platforms": plats})
	return b.Bytes(), err // a template over strings cannot fail to execute
}

// debVersion turns a release tag into a Debian upstream version: "v1.2.3" becomes "1.2.3". Only plain
// vMAJOR.MINOR.PATCH tags are accepted.
func debVersion(tag string) (string, error) {
	v := strings.TrimPrefix(tag, "v")
	parts := strings.Split(v, ".")
	ok := len(parts) == 3 && v != tag
	for _, p := range parts {
		ok = ok && p != "" && len(p) <= 9 && (p == "0" || p[0] != '0')
		for _, c := range p {
			ok = ok && c >= '0' && c <= '9'
		}
	}
	if !ok {
		return "", fmt.Errorf("release: %q is not a vMAJOR.MINOR.PATCH tag", tag)
	}
	return v, nil
}
