// Directory rules: card and group validation, the secrets lint, who may see a
// card, and the find filter. Pure functions, no storage (tier 1).
//
// AUTHORITY BOUNDARY. Everything here is gateway visibility and is advisory
// only (plan.md, "Unauthorized caller": gateway visibility plus the target
// daemon's identity allowlist from the root-signed binding). The gateway never
// holds the allowlist and can only decide what to *show*. A card being visible
// grants nothing: the target daemon checks the caller against the allowlist in
// the signed binding and refuses anyone the binding does not name, whatever this
// module says. Nothing in the gateway may turn "visible" into "permitted", and a
// gateway that hid or showed the wrong cards (a bug or a malicious gateway) can
// change discovery but never access. A card the viewer may not see is simply
// absent, so "not permitted" and "does not exist" look the same.
//
// EVALUATION ORDER (canSee). There are no allow or deny rules, so no precedence
// between them: a card carries one visibility mode and the answer is default
// deny. First match wins, in this order:
//   1. no viewer identity                 -> hidden
//   2. viewer is the card's owner         -> visible (any mode, even "private")
//   3. mode "tenant"                      -> visible to the whole tenant
//   4. mode "groups"                      -> visible iff the viewer belongs to at
//      least one listed group that exists now (a missing, deleted, renamed or
//      empty group has no members, so it matches nobody)
//   5. anything else ("private", or an unknown or malformed mode) -> hidden
// Identities compare case-insensitively. Groups are per tenant (one Tenant DO
// each), so no rule ever sees another tenant's data.

import { cleanText, fold } from "./text";

export const MAX_CARDS_PER_DEVICE = 20;
export const MAX_GROUPS = 100;
export const MAX_MEMBERS = 500;
export const MAX_CARD_GROUPS = 10;
export const MAX_TAGS = 10;
export const MAX_EXAMPLES = 5;
export const MAX_CARDS_PER_TENANT = 2000;
export const MAX_MEMBER_CHARS = 60_000; // total, keeps a group record far below the 128 KiB value limit
export const PAGE_DEFAULT = 25;
export const PAGE_MAX = 100;

// Ids are generated by the gateway, never chosen by a caller: a device id is the
// 16 random bytes of its enrollment request, a card id is that plus 8 bytes of
// the hash of the card name. Anything else is refused before it reaches storage.
const DEVICE_ID = /^[0-9a-f]{32}$/;
const CARD_ID = /^[0-9a-f]{32}:[0-9a-f]{16}$/;
export const isDeviceId = (v: unknown): v is string => typeof v === "string" && DEVICE_ID.test(v);
export const isCardId = (v: unknown): v is string => typeof v === "string" && CARD_ID.test(v);

export type Visibility = "tenant" | "groups" | "private";

// What an owner publishes. Plaintext by design: no secrets belong in it.
export interface Card {
  name: string;
  description: string;
  tags: string[]; // lowercase
  examples: string[];
  visibility: Visibility;
  groups: string[]; // group names; only meaningful for "groups"
}

export interface CardQuery {
  text?: string;
  tag?: string;
}

export type ValidationError = "bad_card" | "bad_group" | "bad_members" | "bad_query";

const VISIBILITY: readonly string[] = ["tenant", "groups", "private"];
// Names are case-insensitive: "Eng" and "eng" are one group.
const groupName = (v: unknown) => (typeof v === "string" ? fold(cleanText(v, 64) ?? "") || null : null);

// Common credential shapes. Best effort: the lint stops accidents, not attackers.
const SECRET_PATTERNS: readonly RegExp[] = [
  /-----BEGIN [A-Z ]*PRIVATE KEY-----/,
  /\bAKIA[0-9A-Z]{16}\b/,
  /\b(?:ghp|gho|ghs|ghu|github_pat)_[A-Za-z0-9_]{20,}/,
  /\bsk-[A-Za-z0-9_-]{20,}/,
  /\bxox[abprs]-[A-Za-z0-9-]{10,}/,
  /\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}/,
  /\b(?:password|passwd|secret|token|api[_-]?key)\s*[:=]\s*\S{8,}/i,
  // Any long unbroken base64 or hex run: pod tokens, signing keys, most API keys.
  /\b[A-Za-z0-9+/_-]{40,}/,
];

// The first field that looks like a secret, or null.
export function lintSecrets(card: Card): keyof Card | null {
  const fields: [keyof Card, string][] = [
    ["name", card.name],
    ["description", card.description],
    ["tags", card.tags.join("\n")],
    ["examples", card.examples.join("\n")],
    ["groups", card.groups.join("\n")],
  ];
  for (const [field, text] of fields) if (SECRET_PATTERNS.some((p) => p.test(text))) return field;
  return null;
}

function strings(v: unknown, max: number, len: number, lower: boolean): string[] | null {
  if (v === undefined) return [];
  if (!Array.isArray(v) || v.length > max) return null;
  const out: string[] = [];
  for (const x of v) {
    const t = typeof x === "string" ? cleanText(x, len) : null;
    if (t === null) return null;
    out.push(lower ? fold(t) : t);
  }
  return [...new Set(out)];
}

export function validateCard(v: unknown): { card: Card } | { error: "bad_card" | "secret_detected"; field?: string } {
  if (!v) return { error: "bad_card" }; // other non-objects have no name and fail below
  const o = v as Record<string, unknown>;
  const name = typeof o.name === "string" ? cleanText(o.name, 64) : null;
  const description = typeof o.description === "string" ? cleanText(o.description, 500) : null;
  const tags = strings(o.tags, MAX_TAGS, 32, true);
  const examples = strings(o.examples, MAX_EXAMPLES, 200, false);
  const visibility = o.visibility ?? "tenant";
  const rawGroups = strings(o.groups, MAX_CARD_GROUPS, 64, true);
  if (!name || !description || !tags || !examples || !rawGroups || !VISIBILITY.includes(visibility as string)) {
    return { error: "bad_card" };
  }
  // A "groups" card needs at least one group; other modes carry none.
  if ((visibility === "groups") !== (rawGroups.length > 0)) return { error: "bad_card" };
  const card: Card = { name, description, tags, examples, visibility: visibility as Visibility, groups: rawGroups };
  const field = lintSecrets(card);
  return field ? { error: "secret_detected", field } : { card };
}

// Group name and member list, normalized (lowercase, de-duplicated).
export function validateGroup(name: unknown, members: unknown): { name: string; members: string[] } | { error: "bad_group" | "bad_members" } {
  const n = groupName(name);
  if (!n) return { error: "bad_group" };
  const m = strings(members, MAX_MEMBERS, 254, true);
  return m && m.reduce((n, x) => n + x.length, 0) <= MAX_MEMBER_CHARS ? { name: n, members: m } : { error: "bad_members" };
}

// The groups a viewer belongs to, given every group as [name, members].
export function memberships(groups: Iterable<[string, readonly string[]]>, viewer: string): Set<string> {
  const out = new Set<string>();
  const who = fold(viewer);
  if (who) for (const [name, members] of groups) if (members.includes(who)) out.add(name);
  return out;
}

// Whether `viewer` may see (and so call) a card. The owner always can.
export function canSee(card: Pick<Card, "visibility" | "groups">, owner: string, viewer: string, viewerGroups: ReadonlySet<string>): boolean {
  if (!viewer) return false;
  if (fold(viewer) === fold(owner)) return true;
  if (card.visibility === "tenant") return true;
  if (card.visibility === "groups") return card.groups.some((g) => viewerGroups.has(g));
  return false;
}

// Name/description substring and exact tag filter; an empty query matches all.
export function matches(card: Pick<Card, "name" | "description" | "tags">, q: CardQuery): boolean {
  const text = q.text?.trim().toLowerCase();
  if (text && !`${card.name}\n${card.description}`.toLowerCase().includes(text)) return false;
  const tag = q.tag?.trim().toLowerCase();
  return !tag || card.tags.includes(tag);
}

export function validateQuery(q: unknown): CardQuery | null {
  if (q === undefined) return {};
  if (!q || typeof q !== "object" || Array.isArray(q)) return null;
  const { text, tag } = q as Record<string, unknown>;
  if ((text !== undefined && (typeof text !== "string" || text.length > 200)) || (tag !== undefined && (typeof tag !== "string" || tag.length > 64))) return null;
  return { text: text as string | undefined, tag: tag as string | undefined };
}

export interface Page {
  limit: number;
  after: string | null; // sort key of the last item of the previous page
}

// `{ limit?, cursor? }` from a request body. The cursor is the hex of a sort key
// (opaque to callers, at most 800 bytes: a member is up to 254 characters); limit defaults to 25 and is at most 100.
export function validatePage(b: { limit?: unknown; cursor?: unknown }): Page | null {
  const { limit, cursor } = b;
  if (limit !== undefined && (!Number.isSafeInteger(limit) || (limit as number) < 1 || (limit as number) > PAGE_MAX)) return null;
  if (cursor === undefined) return { limit: (limit as number | undefined) ?? PAGE_DEFAULT, after: null };
  if (typeof cursor !== "string" || !/^(?:[0-9a-f]{2}){1,800}$/.test(cursor)) return null;
  const bytes = Uint8Array.from(cursor.match(/../g)!, (h) => parseInt(h, 16));
  try {
    return { limit: (limit as number | undefined) ?? PAGE_DEFAULT, after: new TextDecoder("utf-8", { fatal: true, ignoreBOM: false }).decode(bytes) };
  } catch {
    return null;
  }
}

// One page of items already sorted by `key` (plain code-unit order, which a
// cursor can reproduce; never locale order). Items after the cursor key are
// returned, so a page stays stable while others are added or deleted.
export function paginate<T>(sorted: readonly T[], key: (t: T) => string, p: Page): { items: T[]; next_cursor?: string } {
  const rest = p.after === null ? sorted : sorted.filter((t) => key(t) > p.after!);
  const items = rest.slice(0, p.limit);
  if (rest.length <= p.limit) return { items };
  const hex = Array.from(new TextEncoder().encode(key(items[items.length - 1]!)), (b) => b.toString(16).padStart(2, "0")).join("");
  return { items, next_cursor: hex };
}

// Sort key of a card in find results: name, then id. Names hold no newline.
export const cardKey = (c: { name: string; id: string }) => `${c.name.toLowerCase()}\n${c.id}`;
